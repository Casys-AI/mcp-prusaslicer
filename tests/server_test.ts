function minimalGcode(options: {
  header?: string;
  config?: string;
  includeConfig?: boolean;
}): string {
  const header = options.header ??
    "; generated by PrusaSlicer 2.9.2 on 2026-08-05 at 00:09:06 UTC";
  const configLines = options.includeConfig === false ? [] : [
    "; prusaslicer_config = begin",
    options.config ?? "; layer_height = 0.2",
    "; prusaslicer_config = end",
  ];
  return [
    header,
    "; filament used [mm] = 1.00",
    "; filament used [cm3] = 0.01",
    "; filament used [g] = 0.01",
    "; estimated printing time (normal mode) = 1s",
    "; estimated printing time (silent mode) = 2s",
    ...configLines,
    "",
  ].join("\n");
}

async function sha256HexOf(text: string): Promise<string> {
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(text),
  );
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, "0"))
    .join("");
}

