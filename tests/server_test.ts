Deno.test(
  "parseGcodeStats hashes the exact emitted prusaslicer_config block",
  async () => {
    const gcode = await Deno.readTextFile(GCODE_FIXTURE);
    const stats = await parseGcodeStats(gcode);
    const beginMarker = "; prusaslicer_config = begin";
    const endMarker = "; prusaslicer_config = end";
    const beginIdx = gcode.indexOf(beginMarker);
    const endIdx = gcode.indexOf(endMarker, beginIdx);
    assert(beginIdx >= 0 && endIdx > beginIdx, "fixture must contain config markers");
    const block = gcode.slice(beginIdx, endIdx + endMarker.length);
    assertEquals(stats.effective_config_sha256, await sha256HexOf(block));
    assertEquals(stats.effective_config_sha256.length, 64);
  },
);

