Deno.test({
  name: "prusaslicer_estimate_fff: layer_height_mm override changes slice result",
  ignore: !RUN_NATIVE,
  fn: async () => {
    const tool = allTools.find((t) => t.name === "prusaslicer_estimate_fff");
    assert(tool, "tool must exist");

    // Baseline at default 0.2mm layer.
    const base = await tool.handler({
      stl_path: CUBE_20MM_STL,
      profile_ini_path: PROFILE_INI,
    }) as { structuredContent: Record<string, unknown> };

    // 0.3mm layer → fewer layers → less filament and less time.
    const override = await tool.handler({
      stl_path: CUBE_20MM_STL,
      profile_ini_path: PROFILE_INI,
      layer_height_mm: 0.3,
    }) as { structuredContent: Record<string, unknown> };

    const baseMm = base.structuredContent.filament_length_mm as number;
    const overrideMm = override.structuredContent.filament_length_mm as number;
    assert(
      overrideMm < baseMm,
      `layer_height_mm=0.3 should use less filament than 0.2: ${overrideMm} < ${baseMm}`,
    );
    assertEquals(base.structuredContent.overrides_applied, {});
    assertEquals(override.structuredContent.overrides_applied, {
      layer_height_mm: 0.3,
    });
    const baseConfigSummary = base.structuredContent.effective_config_summary as Record<
      string,
      unknown
    >;
    const overrideConfigSummary = override.structuredContent
      .effective_config_summary as Record<string, unknown>;
    const baseConfigValues = baseConfigSummary.values as Record<string, unknown>;
    const overrideConfigValues = overrideConfigSummary.values as Record<
      string,
      unknown
    >;
    assertEquals(
      baseConfigValues.layer_height,
      "0.2",
      "the emitted baseline config must preserve the supplied layer height",
    );
    assertEquals(
      overrideConfigValues.layer_height,
      "0.3",
      "the emitted config must record the forwarded layer-height override",
    );
    assertEquals(
      overrideConfigSummary.config_sha256,
      override.structuredContent.effective_config_sha256,
      "the override summary must remain bound to the actual emitted config block",
    );
    assert(
      base.structuredContent.effective_config_sha256 !==
        override.structuredContent.effective_config_sha256,
      "changing layer_height_mm must change the emitted prusaslicer_config hash",
    );
  },
});

